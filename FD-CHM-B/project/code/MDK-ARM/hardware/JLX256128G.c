//写指令到lcd 
void transfer_command_lcd(int data1) 
{ 
	char i; 
	cs1_L; 
	rs_L; 
	for(i=0;i<8;i++) 
	{ 
	 sclk_L; 
	 if(data1&0x80) sid_H; 
	 else sid_L;
	 sclk_H;
	 data1<<=1;
	}
	cs1_H;
}

//写数据到lcd
void transfer_data_lcd(int data1) 
{ 
	char i; 
	cs1_L; 
	rs_H; 
	for(i=0;i<8;i++) 
	{ 
		sclk_L; 
		if(data1&0x80) sid_H; 
		else sid_L; 
		sclk_H; 
		data1<<=1; 
	} 
	cs1_H; 
}

