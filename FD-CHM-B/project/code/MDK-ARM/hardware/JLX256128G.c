void StringPrint(int x,int y,char *p)
{
	int i;
	y=y*2-1;
	x=((x-1)*8)+1;
	while(*p!='\0')
	{
		lcd_address(x,y,256,16);
		for(i=0;i<8;i++)
		{
			transfer_data_lcd(ASCII_CODE[*p-32][i]);
		}
		lcd_address(x,y+1,256,16);
		for(i=0;i<8;i++)
		{
			transfer_data_lcd(ASCII_CODE[*p-32][i+8]);
		}
		x+=8;
		p++;
	}
}

